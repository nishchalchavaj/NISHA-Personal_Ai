"""NISHA owns memory policy; a local backend owns storage and retrieval."""

from typing import Protocol


class MemoryBackend(Protocol):
    def search(self, text: str, cloud: bool = False, limit: int = 3) -> list[dict]: ...
    def remember(self, text: str, key: str | None = None, category: str = "fact") -> str: ...
    def memories(self) -> list[dict]: ...
    def forget(self, memory_id: str) -> bool: ...
